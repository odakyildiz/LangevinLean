/* Optional browser QA: NODE_PATH=/path/to/node_modules node verify_browser.cjs */
const { chromium } = require('playwright');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');

let browser;
(async () => {
  const screenshotDir = fs.mkdtempSync(path.join(os.tmpdir(), 'langevin-browser-'));
  const installed = chromium.executablePath();
  browser = await chromium.launch({ headless: true, ...(fs.existsSync(installed) ? { executablePath: installed } : { channel: 'chrome' }) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1060 } });
  const errors = [];
  const requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push(request.url()));
  await page.goto(pathToFileURL(path.join(__dirname, 'dist/index.html')).href);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: path.join(screenshotDir, 'langevin-document-top.png') });
  assert.equal(await page.locator('#main-theorem').isVisible(), true);
  await page.locator('#main-theorem').evaluate(el => el.scrollIntoView({ block: 'start', behavior: 'instant' }));
  await page.screenshot({ path: path.join(screenshotDir, 'langevin-main-theorem.png') });
  await page.locator('#main-reference-assumptions > summary').click();
  assert.equal(await page.locator('#main-reference-assumptions').getAttribute('open'), '');
  await page.locator('.main-formal > summary').click();
  assert.equal(await page.locator('.main-formal .lean-code').count(), 2);
  await page.locator('#main-theorem a[href="#decl-unadjustedlangevin-hilbertdalalyan-dalalyan_small_step_of_integral_reference"]').first().click();
  assert.equal(new URL(page.url()).hash, '#decl-unadjustedlangevin-hilbertdalalyan-dalalyan_small_step_of_integral_reference');
  const firstProof = page.locator('.declaration').first();
  await firstProof.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(screenshotDir, 'langevin-document-proof.png') });
  const count = await page.locator('.full-proof').count();
  assert.equal(await page.locator('.full-proof[open]').count(), count);
  await page.locator('#toggle-full').click();
  assert.equal(await page.locator('.full-proof[open]').count(), 0);
  await page.locator('#toggle-full').click();
  assert.equal(await page.locator('.full-proof[open]').count(), count);
  await page.locator('#reading-mode').selectOption('math');
  assert.equal(await page.locator('.pair-code').first().isVisible(), false);
  assert.equal(await page.locator('#toggle-full').isDisabled(), true);
  assert.equal(await page.locator('#toggle-notes').isDisabled(), true);
  assert.equal(await page.locator('#lean-beginner-guide').isVisible(), false);
  await page.locator('#reading-mode').selectOption('paired');
  assert.equal(await page.locator('.pair-code').first().isVisible(), true);
  const firstNote = page.locator('.lean-note[data-note-kind="proof"]').first();
  await firstNote.locator('summary').first().click();
  assert.equal(await firstNote.getAttribute('open'), '');
  assert.ok((await firstNote.locator('.note-body').innerText()).length > 600);
  const typing = firstNote.locator('.symbol-help');
  await typing.locator('summary').click();
  assert.ok((await typing.innerText()).includes('\\^a'));
  await firstNote.evaluate(el => el.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: path.join(screenshotDir, 'langevin-beginner-note-desktop.png') });
  await page.locator('#toggle-notes').click();
  const noteCount = await page.locator('.lean-note').count();
  assert.equal(await page.locator('.lean-note[open]').count(), noteCount);
  await page.locator('#toggle-notes').click();
  assert.equal(await page.locator('.lean-note[open]').count(), 0);
  await firstNote.locator('summary').first().click();
  await firstNote.locator('a[href="#lean-have"]').first().click();
  assert.equal(await page.locator('#lean-have').getAttribute('open'), '');
  await page.goto(pathToFileURL(path.join(__dirname, 'dist/index.html')).href);
  const step = page.locator('.proof-pair[id]').first();
  await step.locator('.code-label a').click();
  assert.equal(await step.evaluate(el => el.classList.contains('selected')), true);
  const firstModule = page.locator('.appendix details').first();
  const moduleId = await firstModule.getAttribute('id');
  await firstProof.locator('.full-proof .source-link').click();
  assert.equal(await firstModule.getAttribute('open'), '');
  assert.equal(new URL(page.url()).hash, '#' + moduleId);
  const downloadPromise = page.waitForEvent('download');
  await firstModule.locator('[data-download]').click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'StrongConvexity.lean');
  await page.setViewportSize({ width: 390, height: 844 });
  await firstProof.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(screenshotDir, 'langevin-document-mobile.png') });
  await firstNote.locator('summary').first().click();
  await firstNote.evaluate(el => el.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: path.join(screenshotDir, 'langevin-beginner-note-mobile.png') });
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.locator('#lean-unicode').evaluate(el => { el.open = true; });
    const overflow = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, offenders: [...document.querySelectorAll('body *')].filter(el => el.getBoundingClientRect().right > innerWidth && !el.closest('.lean-code,.katex-display,.katex-mathml')).slice(0,15).map(el => [el.tagName, el.className, el.getBoundingClientRect().right, el.textContent.slice(0,90)]) }));
    assert.equal(overflow.width > width, false, `Page overflows at ${width}px: ${JSON.stringify(overflow)}`);
  }
  const brokenFonts = await page.evaluate(() => [...document.fonts].filter(font => font.status === 'error').length);
  assert.equal(brokenFonts, 0);
  assert.deepEqual(errors, []);
  assert.equal(requests.some(url => /^https?:/.test(url)), false, 'Page requests network resources');
  console.log(`Browser verified: ${count} full proofs, ${noteCount} beginner notes; note controls, symbol typing tables, glossary links, folding, reading modes, step links, module links, downloads, embedded fonts, 320–1440px layout; no runtime errors or network requests.`);
  console.log(`Screenshots: ${screenshotDir}`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
