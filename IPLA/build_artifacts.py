TEX = re.compile(r'\\\[(.*?)\\\]|\\\((.*?)\\\)', re.S)


def mathematics(text):
    formulas = [(m[1] is not None, m[1] or m[2]) for m in TEX.finditer(text)]
    js = """const fs=require('fs'),k=require(process.argv[1]);
process.stdout.write(JSON.stringify(JSON.parse(fs.readFileSync(0,'utf8')).map(
 ([displayMode,t])=>k.renderToString(t,{displayMode,throwOnError:true,
 strict:'ignore',output:'htmlAndMathml',trust:false}))));"""
    result = subprocess.run(['node', '-e', js, str(VENDOR/'katex.min.js')],
                            input=json.dumps(formulas), text=True, capture_output=True, check=True)
    rendered = iter(json.loads(result.stdout))
    return TEX.sub(lambda m: '<div class="math">'+next(rendered)+'</div>'
                   if m[1] is not None else next(rendered), text)


def markdown(text):
    # Protect fenced code before math, then extract math before ordinary
    # Markdown processing so formula pipes cannot become table separators.
    raw = []
    def token(s):
        raw.append(s)
        return f'@@RAW{len(raw)-1}@@'
    text = re.sub(r'```[^\n]*\n(.*?)```',
                  lambda m: token('<pre><code>'+html.escape(m[1])+'</code></pre>'), text, flags=re.S)
    text = TEX.sub(lambda m: token(mathematics(m[0])), text)
    def inline(s):
        def code_link(match):
            value = match[1]
            linked = (re.fullmatch(r'(?:IPLA|UnadjustedLangevin)/[\w/]+\.lean',
                                  value) and (ROOT/value).is_file())
            return token('<code>' + (lean_link(value) if linked else html.escape(value)) + '</code>')
        s = re.sub(r'`([^`]+)`', code_link, s)
        s = html.escape(s)
        s = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', r'<a href="\2">\1</a>', s)
        s = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', s)
        s = re.sub(r'\*([^*]+)\*', r'<em>\1</em>', s)
        return s
    out, para, listing = [], [], None
    def flush():
        if para:
            out.append('<p>'+inline(' '.join(para))+'</p>')
            para.clear()
    def close_list():
        nonlocal listing
        if listing:
            out.append(f'</{listing}>')
            listing = None
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        s = lines[i].strip()
        if not s:
            flush(); close_list(); i += 1; continue
        if s.startswith('|'):
            flush(); close_list()
            rows = []
            while i < len(lines) and lines[i].strip().startswith('|'):
                cells = [x.strip() for x in lines[i].strip().strip('|').split('|')]
                if not all(re.fullmatch(r':?-+:?', x.replace(' ', '')) for x in cells):
                    tag = 'th' if not rows else 'td'
                    attrs = ' scope="col"' if tag == 'th' else ''
                    rows.append('<tr>'+''.join(f'<{tag}{attrs}>'+inline(x)+f'</{tag}>' for x in cells)+'</tr>')
                i += 1
            header = '<thead>'+rows[0]+'</thead>' if rows else ''
            body = '<tbody>'+''.join(rows[1:])+'</tbody>' if len(rows) > 1 else ''
            out.append('<div class="table-wrap"><table>'+header+body+'</table></div>')
            continue
        heading = re.match(r'^(#{1,4}) (.*)', s)
        bullet = re.match(r'^(- |\d+\. )(.*)', s)
        if heading:
            flush(); close_list()
            level = len(heading[1]); title = heading[2]
            anchor_title = re.sub(r'@@RAW\d+@@', '', title)
            anchor = re.sub('[^a-z0-9]+', '-', anchor_title.lower()).strip('-')
            out.append(f'<h{level} id="{anchor}">'+inline(title)+f'</h{level}>')
        elif bullet:
            flush()
            tag = 'ul' if bullet[1] == '- ' else 'ol'
            if listing != tag:
                close_list(); out.append(f'<{tag}>'); listing = tag
            out.append('<li>'+inline(bullet[2])+'</li>')
        elif re.fullmatch(r'@@RAW\d+@@', s):
            flush(); close_list(); out.append(s)
        else:
            if listing and out and out[-1].endswith('</li>'):
                out[-1] = out[-1][:-5] + ' ' + inline(s) + '</li>'
            else:
                para.append(s)
        i += 1
    flush(); close_list()
    result = '\n'.join(out)
    # Nested replacements occur when formulas sit within a paragraph or table.
    for _ in range(3):
        result = re.sub(r'@@RAW(\d+)@@', lambda m: raw[int(m[1])], result)
    if '@@RAW' in result:
        raise ValueError('Unresolved rendering token')
    return result


def katex_css():
    def embed(m):
        encoded = base64.b64encode((VENDOR/m[1]).read_bytes()).decode()
        return 'src:url(data:font/woff2;base64,'+encoded+') format("woff2")'
    return re.sub(r'src:url\((fonts/[^)]+\.woff2)\)[^}]+', embed,
                  (VENDOR/'katex.min.css').read_text())


