def lean_closure():
    ordered, external, seen = [], [], set()
    def visit(name):
        if name in seen:
            return
        seen.add(name)
        path = ROOT / (name.replace('.', '/') + '.lean')
        if not path.exists():
            if not name.startswith('Mathlib.'):
                raise ValueError(f'Unexpected external dependency: {name}')
            external.append(name)
            return
        source = path.read_text()
        for dep in re.findall(r'^import ([\w.]+)\s*$', source, re.M):
            visit(dep)
        ordered.append((path.relative_to(ROOT).as_posix(), source))
    visit('IPLA.Theorem')
    return ordered, external


